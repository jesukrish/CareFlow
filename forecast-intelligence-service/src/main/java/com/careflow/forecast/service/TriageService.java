package com.careflow.forecast.service;

import com.careflow.forecast.dto.TriageRequest;
import com.careflow.forecast.dto.TriageResponse;
import com.careflow.forecast.dto.ForecastResponse.ContributingFactor;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.stereotype.Service;

import java.util.*;

/**
 * Demonstration rule-based triage engine.
 * DISCLAIMER: This is a decision-support prototype for demonstration purposes only.
 * It is NOT a validated clinical tool and must NOT be used for actual clinical decisions.
 * Thresholds are based on published emergency triage guidelines (ESI, MTS) but have not
 * been clinically validated in this implementation.
 */
@Service
public class TriageService {

    private static final Logger log = LoggerFactory.getLogger(TriageService.class);
    private static final String DISCLAIMER =
            "This triage assessment is generated by a demonstration decision-support prototype. " +
            "It is NOT a validated clinical tool. All clinical decisions must be made by qualified " +
            "healthcare professionals. This system should only be used as a supplementary reference.";

    private final GeminiService geminiService;

    public TriageService(GeminiService geminiService) {
        this.geminiService = geminiService;
    }

    public TriageResponse assessTriage(TriageRequest request) {
        TriageResponse response = new TriageResponse();
        response.setDisclaimer(DISCLAIMER);

        List<String> rulesTriggered = new ArrayList<>();
        List<ContributingFactor> factors = new ArrayList<>();
        int highestPriority = 5; // Start with lowest (NON_URGENT)

        // === IMMEDIATE (Level 1) Symptoms — never down-ranked ===
        Set<String> immediateSymptoms = Set.of(
                "cardiac arrest", "respiratory arrest", "unresponsive",
                "severe hemorrhage", "anaphylaxis", "major trauma",
                "active seizure", "no pulse"
        );
        for (String symptom : request.getSymptoms()) {
            if (immediateSymptoms.contains(symptom.toLowerCase().trim())) {
                highestPriority = 1;
                rulesTriggered.add("IMMEDIATE: Life-threatening symptom detected - " + symptom);
                factors.add(new ContributingFactor("Critical Symptom", symptom + " requires immediate intervention", "HIGH"));
            }
        }

        // === EMERGENT (Level 2) Symptoms ===
        Set<String> emergentSymptoms = Set.of(
                "chest pain", "severe breathing difficulty", "stroke symptoms",
                "altered consciousness", "severe burns", "acute confusion",
                "severe abdominal pain", "high-risk mechanism injury",
                "severe allergic reaction", "suicidal ideation"
        );
        for (String symptom : request.getSymptoms()) {
            if (emergentSymptoms.contains(symptom.toLowerCase().trim())) {
                highestPriority = Math.min(highestPriority, 2);
                rulesTriggered.add("EMERGENT: High-risk symptom - " + symptom);
                factors.add(new ContributingFactor("High-Risk Symptom", symptom + " indicates emergent condition", "HIGH"));
            }
        }

        // === URGENT (Level 3) Symptoms ===
        Set<String> urgentSymptoms = Set.of(
                "moderate pain", "vomiting blood", "abdominal pain",
                "high fever", "persistent vomiting", "dehydration signs",
                "fracture", "laceration requiring sutures", "asthma exacerbation"
        );
        for (String symptom : request.getSymptoms()) {
            if (urgentSymptoms.contains(symptom.toLowerCase().trim())) {
                highestPriority = Math.min(highestPriority, 3);
                rulesTriggered.add("URGENT: Symptom requiring timely attention - " + symptom);
                factors.add(new ContributingFactor("Urgent Symptom", symptom, "MEDIUM"));
            }
        }

        // === LESS URGENT (Level 4) Symptoms ===
        Set<String> lessUrgentSymptoms = Set.of(
                "mild pain", "minor injury", "earache", "sore throat",
                "mild rash", "urinary symptoms", "mild fever", "headache"
        );
        for (String symptom : request.getSymptoms()) {
            if (lessUrgentSymptoms.contains(symptom.toLowerCase().trim())) {
                highestPriority = Math.min(highestPriority, 4);
                rulesTriggered.add("LESS URGENT: Non-critical symptom - " + symptom);
                factors.add(new ContributingFactor("Minor Symptom", symptom, "LOW"));
            }
        }

        // === Vital Signs Assessment ===
        if (request.getVitalSigns() != null && !request.getVitalSigns().isEmpty()) {
            Map<String, Double> vitals = request.getVitalSigns();

            // Heart rate
            Double hr = vitals.get("heartRate");
            if (hr != null) {
                if (hr > 150 || hr < 40) {
                    highestPriority = Math.min(highestPriority, 1);
                    rulesTriggered.add("IMMEDIATE: Critical heart rate - " + hr.intValue() + " bpm");
                    factors.add(new ContributingFactor("Heart Rate", hr.intValue() + " bpm (critical range)", "HIGH"));
                } else if (hr > 120 || hr < 50) {
                    highestPriority = Math.min(highestPriority, 2);
                    rulesTriggered.add("EMERGENT: Abnormal heart rate - " + hr.intValue() + " bpm");
                    factors.add(new ContributingFactor("Heart Rate", hr.intValue() + " bpm (abnormal)", "HIGH"));
                } else if (hr > 100 || hr < 60) {
                    highestPriority = Math.min(highestPriority, 3);
                    rulesTriggered.add("URGENT: Borderline heart rate - " + hr.intValue() + " bpm");
                    factors.add(new ContributingFactor("Heart Rate", hr.intValue() + " bpm (borderline)", "MEDIUM"));
                }
            }

            // Oxygen saturation
            Double spo2 = vitals.get("oxygenSaturation");
            if (spo2 != null) {
                if (spo2 < 85) {
                    highestPriority = Math.min(highestPriority, 1);
                    rulesTriggered.add("IMMEDIATE: Critical hypoxia - SpO2 " + spo2.intValue() + "%");
                    factors.add(new ContributingFactor("Oxygen Saturation", "SpO2 " + spo2.intValue() + "% (critical)", "HIGH"));
                } else if (spo2 < 90) {
                    highestPriority = Math.min(highestPriority, 2);
                    rulesTriggered.add("EMERGENT: Severe hypoxia - SpO2 " + spo2.intValue() + "%");
                    factors.add(new ContributingFactor("Oxygen Saturation", "SpO2 " + spo2.intValue() + "% (severe)", "HIGH"));
                } else if (spo2 < 94) {
                    highestPriority = Math.min(highestPriority, 3);
                    rulesTriggered.add("URGENT: Low oxygen - SpO2 " + spo2.intValue() + "%");
                    factors.add(new ContributingFactor("Oxygen Saturation", "SpO2 " + spo2.intValue() + "% (low)", "MEDIUM"));
                }
            }

            // Temperature
            Double temp = vitals.get("temperature");
            if (temp != null) {
                if (temp >= 41.0 || temp < 33.0) {
                    highestPriority = Math.min(highestPriority, 2);
                    rulesTriggered.add("EMERGENT: Extreme temperature - " + temp + "°C");
                    factors.add(new ContributingFactor("Temperature", temp + "°C (extreme)", "HIGH"));
                } else if (temp >= 39.0) {
                    highestPriority = Math.min(highestPriority, 3);
                    rulesTriggered.add("URGENT: High fever - " + temp + "°C");
                    factors.add(new ContributingFactor("Temperature", temp + "°C (high fever)", "MEDIUM"));
                } else if (temp >= 38.0) {
                    highestPriority = Math.min(highestPriority, 4);
                    rulesTriggered.add("LESS URGENT: Fever - " + temp + "°C");
                    factors.add(new ContributingFactor("Temperature", temp + "°C (fever)", "LOW"));
                }
            }

            // Respiratory rate
            Double rr = vitals.get("respiratoryRate");
            if (rr != null) {
                if (rr > 35 || rr < 8) {
                    highestPriority = Math.min(highestPriority, 1);
                    rulesTriggered.add("IMMEDIATE: Critical respiratory rate - " + rr.intValue() + "/min");
                    factors.add(new ContributingFactor("Respiratory Rate", rr.intValue() + "/min (critical)", "HIGH"));
                } else if (rr > 25 || rr < 10) {
                    highestPriority = Math.min(highestPriority, 2);
                    rulesTriggered.add("EMERGENT: Abnormal respiratory rate - " + rr.intValue() + "/min");
                    factors.add(new ContributingFactor("Respiratory Rate", rr.intValue() + "/min (abnormal)", "HIGH"));
                }
            }

            // Blood pressure (systolic)
            Double sbp = vitals.get("systolicBP");
            if (sbp != null) {
                if (sbp < 70 || sbp > 220) {
                    highestPriority = Math.min(highestPriority, 1);
                    rulesTriggered.add("IMMEDIATE: Critical blood pressure - SBP " + sbp.intValue() + " mmHg");
                    factors.add(new ContributingFactor("Blood Pressure", "Systolic " + sbp.intValue() + " mmHg (critical)", "HIGH"));
                } else if (sbp < 90 || sbp > 180) {
                    highestPriority = Math.min(highestPriority, 2);
                    rulesTriggered.add("EMERGENT: Abnormal blood pressure - SBP " + sbp.intValue() + " mmHg");
                    factors.add(new ContributingFactor("Blood Pressure", "Systolic " + sbp.intValue() + " mmHg (abnormal)", "HIGH"));
                }
            }
        }

        // Age-based risk adjustment (pediatric and elderly are higher risk)
        if (request.getAgeGroup() != null) {
            if ("0-17".equals(request.getAgeGroup()) && highestPriority > 3) {
                highestPriority = Math.min(highestPriority, highestPriority); // Don't auto-escalate, just note
                factors.add(new ContributingFactor("Age Group", "Pediatric patient - requires age-appropriate assessment", "MEDIUM"));
                rulesTriggered.add("NOTE: Pediatric patient - apply age-appropriate clinical thresholds");
            } else if ("75+".equals(request.getAgeGroup()) && highestPriority > 3) {
                highestPriority = Math.min(highestPriority, 3);
                factors.add(new ContributingFactor("Age Group", "Elderly patient (75+) - elevated risk profile", "MEDIUM"));
                rulesTriggered.add("ESCALATED: Elderly patient (75+) - increased baseline risk");
            }
        }

        // No rules triggered = non-urgent
        if (rulesTriggered.isEmpty()) {
            rulesTriggered.add("NON-URGENT: No high-priority symptoms or abnormal vitals detected");
            factors.add(new ContributingFactor("Overall Assessment", "No critical findings identified", "LOW"));
        }

        // Set priority
        response.setPriorityLevel(highestPriority);
        response.setPriorityCategory(getPriorityCategory(highestPriority));
        response.setPriorityColor(getPriorityColor(highestPriority));
        response.setRulesTriggered(rulesTriggered);
        response.setContributingFactors(factors);
        response.setExplanation(buildExplanation(highestPriority, rulesTriggered));

        // Gemini explanation
        try {
            String geminiExplanation = geminiService.explainTriage(response, request);
            response.setGeminiExplanation(geminiExplanation);
        } catch (Exception e) {
            log.warn("Gemini triage explanation failed: {}", e.getMessage());
            response.setGeminiExplanation(response.getExplanation());
        }

        return response;
    }

    private String getPriorityCategory(int level) {
        return switch (level) {
            case 1 -> "IMMEDIATE";
            case 2 -> "EMERGENT";
            case 3 -> "URGENT";
            case 4 -> "LESS_URGENT";
            default -> "NON_URGENT";
        };
    }

    private String getPriorityColor(int level) {
        return switch (level) {
            case 1 -> "RED";
            case 2 -> "ORANGE";
            case 3 -> "YELLOW";
            case 4 -> "GREEN";
            default -> "BLUE";
        };
    }

    private String buildExplanation(int level, List<String> rules) {
        String category = getPriorityCategory(level);
        StringBuilder sb = new StringBuilder();
        sb.append("Triage Priority: Level ").append(level).append(" - ").append(category).append(". ");
        sb.append("Based on ").append(rules.size()).append(" rule(s) evaluated: ");
        for (int i = 0; i < Math.min(3, rules.size()); i++) {
            sb.append(rules.get(i));
            if (i < Math.min(3, rules.size()) - 1) sb.append("; ");
        }
        if (rules.size() > 3) {
            sb.append(" (+").append(rules.size() - 3).append(" more)");
        }
        return sb.toString();
    }
}
